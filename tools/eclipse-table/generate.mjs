// Generates packages/core/src/ext/eclipses.ts (T29) from NASA's Besselian elements CSV:
//   curl -o bess.csv https://eclipse.gsfc.nasa.gov/eclipse_besselian_from_mysqldump2.csv
//   node tools/eclipse-table/generate.mjs bess.csv > packages/core/src/ext/eclipses.ts
// Only years FROM..TO; numbers as in the CSV.
import { readFileSync } from 'node:fs';

const FROM = 2025;
const TO = 2035;
const [file] = process.argv.slice(2);
if (file === undefined) throw new Error('usage: generate.mjs <besselian.csv>');
const lines = readFileSync(file, 'latin1')
  .split(/\r?\n/)
  .filter((l) => l.trim() !== '');
const split = (l) => l.split(',').map((c) => c.replace(/^"|"$/g, ''));
const head = split(lines[0]);
const col = (r, name) => {
  const i = head.indexOf(name);
  if (i < 0) throw new Error(`no column ${name}`);
  return r[i];
};
const num = (s) => {
  const n = Number(s);
  if (!Number.isFinite(n)) throw new Error(`bad number ${s}`);
  return n;
};
const rows = [];
for (const l of lines.slice(1)) {
  const r = split(l);
  const year = num(col(r, 'year'));
  if (year < FROM || year > TO) continue;
  const p = (names) => names.map((n) => num(col(r, n)));
  rows.push({
    date: `${year}-${String(num(col(r, 'month'))).padStart(2, '0')}-${String(num(col(r, 'day'))).padStart(2, '0')}`,
    type: col(r, 'eclipse_type'),
    dt: num(col(r, 'dt')),
    t0: num(col(r, 't0')),
    x: p(['x0', 'x1', 'x2', 'x3']),
    y: p(['y0', 'y1', 'y2', 'y3']),
    d: p(['d0', 'd1', 'd2']),
    mu: p(['mu0', 'mu1', 'mu2']),
    l1: p(['l10', 'l11', 'l12']),
    l2: p(['l20', 'l21', 'l22']),
    tanF1: num(col(r, 'tan_f1')),
    tanF2: num(col(r, 'tan_f2')),
    tMin: num(col(r, 'tmin')),
    tMax: num(col(r, 'tmax')),
  });
}
const arr = (a) => `[${a.join(', ')}]`;
const out = [
  '/**',
  ' * Besselian elements of the solar eclipses ' +
    FROM +
    '–' +
    TO +
    ' (T29): NASA, Fred Espenak and Jean Meeus,',
  ' * "Five Millennium Canon of Solar Eclipses: -1999 to +3000" (NASA/TP-2006-214141), catalogue of',
  ' * Besselian elements https://eclipse.gsfc.nasa.gov/eclipse_besselian_from_mysqldump2.csv, taken',
  ' * 2026-10-09. "Permission is freely granted to reproduce any portion of this NASA Reference',
  ' * Publication. All uses and/or publication of this material should be accompanied by an',
  ' * appropriate acknowledgment of the source." (https://eclipse.gsfc.nasa.gov/SEpubs/5MCSE.html).',
  ' * GENERATED by tools/eclipse-table/generate.mjs — do not edit by hand.',
  ' *',
  ' * `date` — calendar date of greatest eclipse; `t0` — reference hour TD on that date; `dt` — ΔT, s;',
  ' * polynomials in t = TD hours − t0 (x, y, l1, l2 in Earth radii; d, mu in degrees); `type` — catalogue',
  ' * type (T total, A annular, H hybrid, P partial, with suffixes).',
  ' */',
  '',
  'export interface BesselianElements {',
  '  readonly date: string;',
  '  readonly type: string;',
  '  readonly dt: number;',
  '  readonly t0: number;',
  '  readonly x: readonly [number, number, number, number];',
  '  readonly y: readonly [number, number, number, number];',
  '  readonly d: readonly [number, number, number];',
  '  readonly mu: readonly [number, number, number];',
  '  readonly l1: readonly [number, number, number];',
  '  readonly l2: readonly [number, number, number];',
  '  readonly tanF1: number;',
  '  readonly tanF2: number;',
  '  readonly tMin: number;',
  '  readonly tMax: number;',
  '}',
  '',
  "export const ECLIPSE_SOURCE = 'NASA 5MCSE (ESPENAK, MEEUS)';",
  '',
  'export const SOLAR_ECLIPSES: readonly BesselianElements[] = [',
  ...rows.map(
    (e) =>
      `  {\n    date: '${e.date}',\n    type: '${e.type}',\n    dt: ${e.dt},\n    t0: ${e.t0},\n    x: ${arr(e.x)},\n    y: ${arr(e.y)},\n    d: ${arr(e.d)},\n    mu: ${arr(e.mu)},\n    l1: ${arr(e.l1)},\n    l2: ${arr(e.l2)},\n    tanF1: ${e.tanF1},\n    tanF2: ${e.tanF2},\n    tMin: ${e.tMin},\n    tMax: ${e.tMax},\n  },`,
  ),
  '];',
  '',
];
process.stdout.write(out.join('\n'));
