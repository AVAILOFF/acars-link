// Collects licence texts of what the installer ships (T19) into
// apps/desktop/build/third-party-licenses.txt (generated, gitignored; electron-builder copies it
// to resources/). Run by `pnpm desktop:dist`. Fails loudly instead of skipping a missing text.
//
// Shipped npm packages: renderer (react, react-dom, scheduler, zustand) and the main bundle
// (ajv and its dependencies, yaml). .NET: the self-contained bridge carries the runtime packs.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const pnpmStore = join(root, 'node_modules/.pnpm');
const nugetRoot = process.env.NUGET_PACKAGES ?? join(homedir(), '.nuget/packages');

const npmPackages = [
  'react',
  'react-dom',
  'scheduler',
  'zustand',
  'ajv',
  'fast-deep-equal',
  'fast-uri',
  'json-schema-traverse',
  'require-from-string',
  'yaml',
];
const dotnetPacks = [
  'microsoft.netcore.app.runtime.win-x64',
  'microsoft.aspnetcore.app.runtime.win-x64',
];

const out = [
  'Third-party licence texts for ACARS Link. Generated by tools/licenses/collect.mjs.',
  'Electron and Chromium licences are in LICENSE.electron.txt and LICENSES.chromium.html.',
  '',
];
const section = (title, text) => out.push('='.repeat(78), title, '='.repeat(78), text.trim(), '');
const licenceFile = (dir) => readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f));

for (const name of npmPackages) {
  const entry = readdirSync(pnpmStore).find((d) => d.startsWith(`${name.replace('/', '+')}@`));
  if (!entry) throw new Error(`${name}: not found in node_modules/.pnpm (run pnpm install)`);
  const dir = join(pnpmStore, entry, 'node_modules', name);
  const file = licenceFile(dir);
  if (!file) throw new Error(`${name}: no licence file in ${dir}`);
  const { version, license } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  section(`${name} ${version} (${license})`, readFileSync(join(dir, file), 'utf8'));
}

for (const pack of dotnetPacks) {
  const packDir = join(nugetRoot, pack);
  if (!existsSync(packDir))
    throw new Error(`${pack}: not found in ${nugetRoot} (run pnpm bridge:publish)`);
  const version = readdirSync(packDir).sort().at(-1);
  const dir = join(packDir, version);
  const files = readdirSync(dir).filter((f) => /^(license|third-party-notices)\.txt$/i.test(f));
  if (files.length === 0) throw new Error(`${pack}: no licence files in ${dir}`);
  for (const f of files) section(`${pack} ${version}: ${f}`, readFileSync(join(dir, f), 'utf8'));
}

writeFileSync(
  join(root, 'apps/desktop/build/third-party-licenses.txt'),
  `${out.join('\n')}\n`,
  'utf8',
);
console.log(
  `third-party-licenses.txt: ${npmPackages.length} npm packages, ${dotnetPacks.length} .NET packs`,
);
